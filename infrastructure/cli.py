"""Composition root. `python -m infrastructure.cli run-all` = six feature calls + task x model matrix + report files."""
from __future__ import annotations

import json
import sys
import time
from concurrent.futures import ThreadPoolExecutor

from adapters.otari_http import OtariHttp
from application.features import FeatureConfig, run_features
from application.porting import run_matrix
from domain.catalog import build_tasks
from domain.tasks import ModelRef, Verdict
from infrastructure import config
from infrastructure.logsink import JsonlSink


def _wait_ready(gw: OtariHttp, tries: int = 60) -> None:
    import urllib.request
    for _ in range(tries):
        try:
            urllib.request.urlopen(gw.base + gw.prefix + "/health", timeout=3)
            return
        except Exception:
            time.sleep(2)
    raise SystemExit("gateway not ready at " + gw.base)


def build(settings, fresh=True):
    sink = JsonlSink("logs/http.jsonl", fresh=fresh)
    return OtariHttp(settings.base_url, settings.api_key, sink, master_key=settings.master_key, api_prefix=settings.api_prefix)


def cmd_features(gw, s, out):
    m_small, m_large, m_base = s.models
    cfg = FeatureConfig(policy=s.policy, worker=m_small.selector, judge=m_large.selector, baseline=m_base.selector, capped_key=s.capped_key)
    rep = run_features(gw, cfg, time.sleep)
    with open("logs/features.jsonl", "w") as f:
        for t in rep.traces:
            f.write(json.dumps({"feature": t.kind.value, "request_id": t.request_id, "model": t.model, "evidence": t.evidence}, ensure_ascii=False) + "\n")
    with open("logs/enforcements.jsonl", "w") as f:
        for rid, e, ref in rep.enforcements:
            f.write(json.dumps({"request_id": rid, "rule": e.rule, "status": e.status, "upstream_called": e.upstream_called, "log_ref": ref}) + "\n")
    out["features"] = {"score": rep.score, "used": [t.kind.value for t in rep.traces], "failures": rep.failures, "attempts": rep.attempts}
    print("FEATURES score=%d/60 used=%s failures=%s" % (rep.score, [t.kind.value for t in rep.traces], rep.failures))


def cmd_matrix(gw, s, out):
    tasks = build_tasks()
    with ThreadPoolExecutor(max_workers=s.workers) as pool:
        mx = run_matrix(gw, tasks, s.models, time.sleep, pool_map=pool.map)
    md = mx.to_markdown()
    broken = ["- %s x %s (%s): %s%s %s" % (tid, m.model, m.role, c.verdict.value, " [" + c.note + "]" if c.note else "", ("answer=" + repr(c.answer[:80])) if c.answer else "")
              for tid, m, c in mx.broken()]
    with open("results/matrix.md", "w") as f:
        f.write("# Task x model result matrix\n\nGenerated by `python -m infrastructure.cli matrix` (%s). pass = deterministic check passed; "
                "fail = model answered, check rejected it; blocked = gateway/upstream error after 6 tries (no answer to judge).\n\n%s\n\n## Where it breaks\n\n%s\n"
                % (time.strftime("%Y-%m-%d %H:%M"), md, "\n".join(broken) or "- none"))
    with open("results/matrix.json", "w") as f:
        json.dump({"%s|%s" % k: {"verdict": c.verdict.value, "answer": c.answer, "note": c.note, "request_id": c.request_id} for k, c in mx.cells.items()}, f, ensure_ascii=False, indent=1)
    out["matrix"] = {m.selector: "%d/%d" % mx.pass_rate(m) for m in s.models}
    print(md)


def cmd_judge(gw, s, out):
    from application.judging import run_judge_agreement, summarize
    from domain.catalog import KNOWN_BAD
    from infrastructure import render
    worker, judge = s.models[0], s.models[1]
    mx = render.load_matrix("results/matrix.json", s.models)
    with ThreadPoolExecutor(max_workers=s.workers) as pool:
        cells = run_judge_agreement(gw, build_tasks(), mx, worker, judge.selector, KNOWN_BAD, time.sleep, pool_map=pool.map)
    summ = summarize(cells)
    with open("results/judge.json", "w") as f:
        json.dump({"judge": judge.selector, "worker": worker.selector, "summary": summ,
                   "cells": [dict(task_id=c.task_id, kind=c.kind, truth=c.truth, said=c.said, request_id=c.request_id) for c in cells]}, f, indent=1)
    out["judge"] = summ
    print("JUDGE", summ)


def cmd_replay(write_readme: bool) -> int:
    """No gateway, no keys: rebuild the tables from the committed result files (the 3-minute check)."""
    from infrastructure import render
    models = [ModelRef("gemma_small", "gemma-4-26b-a4b-it", "worker"), ModelRef("gemma_large", "gemma-4-31b-it", "judge"),
              ModelRef("baseline", "gemini-3.5-flash-lite", "baseline")]
    mx = render.load_matrix("results/matrix.json", models)
    mtab, ftab = mx.to_markdown(), render.features_markdown("logs/features.jsonl")
    jtab = render.judge_markdown("results/judge.json")
    print(mtab + "\n\n" + ftab + "\n\n" + render.provider_stats_markdown("logs/http.jsonl") + "\n\n" + jtab)
    if write_readme:
        t = open("README.md").read()
        t = render.replace_block(t, "matrix", mtab)
        t = render.replace_block(t, "features", ftab)
        t = render.replace_block(t, "providers", render.provider_stats_markdown("logs/http.jsonl"))
        t = render.replace_block(t, "judge", jtab)
        open("README.md", "w").write(t)
    return 0


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "run-all"
    if cmd == "replay":
        return cmd_replay("--write-readme" in argv)
    s = config.load()
    gw = build(s, fresh=(cmd == "run-all"))
    _wait_ready(gw)
    out = {}
    if cmd in ("features", "run-all"):
        cmd_features(gw, s, out)
    if cmd in ("matrix", "run-all"):
        cmd_matrix(gw, s, out)
    if cmd in ("judge", "run-all"):
        cmd_judge(gw, s, out)
    out["finished"] = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    if cmd == "run-all":
        with open("results/summary.json", "w") as f:
            json.dump(out, f, ensure_ascii=False, indent=1)
    ok = out.get("features", {}).get("score", 0) == 60 or cmd in ("matrix", "judge")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
